/**
 * Size Guide — browser-side template generation.
 *
 * Builds clean and guide templates as SVG text, then hands them to the browser
 * as a Blob download. Nothing leaves the page and no external service is used.
 */
( function ( window, document ) {
	'use strict';

	var SizeGuide = window.SizeGuide || ( window.SizeGuide = {} );
	var Convert = SizeGuide.Convert;
	var Infographic = SizeGuide.Infographic;

	/**
	 * Trim a number for SVG output.
	 *
	 * @param {number} value Number.
	 * @return {string} Clean number.
	 */
	function num( value ) {
		return String( Math.round( ( parseFloat( value ) || 0 ) * 1000 ) / 1000 );
	}

	/**
	 * Escape text for XML.
	 *
	 * @param {string} value Raw text.
	 * @return {string} Escaped text.
	 */
	function escapeXml( value ) {
		return String( value == null ? '' : value )
			.replace( /&/g, '&amp;' )
			.replace( /</g, '&lt;' )
			.replace( />/g, '&gt;' )
			.replace( /"/g, '&quot;' )
			.replace( /'/g, '&apos;' );
	}

	var Templates = {

		/**
		 * Build an SVG document for a format.
		 *
		 * @param {Object} format  Format record.
		 * @param {string} type    "clean" or "guide".
		 * @param {Object} strings Translated labels.
		 * @return {string} SVG source.
		 */
		buildSvg: function ( format, type, strings ) {
			strings = strings || {};

			var geo = Infographic.geometry( format, {} );
			var unitSuffix = 'px' === format.unit ? '' : format.unit;
			var scale = Math.max( geo.docWidth, geo.docHeight );
			var stroke = scale / 600;
			var font = scale / 45;
			var parts = [];

			parts.push( '<?xml version="1.0" encoding="UTF-8"?>' );
			parts.push(
				'<svg xmlns="http://www.w3.org/2000/svg" width="' + num( geo.docWidth ) + unitSuffix +
				'" height="' + num( geo.docHeight ) + unitSuffix +
				'" viewBox="0 0 ' + num( geo.docWidth ) + ' ' + num( geo.docHeight ) + '">'
			);

			parts.push( '<title>' + escapeXml( format.platform_name + ' — ' + format.name ) + '</title>' );
			parts.push(
				'<desc>' + escapeXml(
					Convert.dimensions( format.width, format.height, format.unit ) +
					', ' + format.aspect_ratio + '. Generated by the Size Guide plugin.'
				) + '</desc>'
			);

			parts.push(
				'<rect x="0" y="0" width="' + num( geo.docWidth ) + '" height="' + num( geo.docHeight ) +
				'" fill="#ffffff"/>'
			);

			if ( 'clean' === type ) {
				parts.push( '</svg>' );
				return parts.join( '\n' );
			}

			parts.push( '<g id="size-guide-guides" fill="none">' );

			if ( geo.bleed > 0 ) {
				parts.push(
					'<rect x="0" y="0" width="' + num( geo.docWidth ) + '" height="' + num( geo.docHeight ) +
					'" stroke="' + Infographic.COLORS.bleed + '" stroke-width="' + num( stroke ) +
					'" stroke-dasharray="' + num( stroke * 6 ) + '"/>'
				);
			}

			parts.push(
				'<rect x="' + num( geo.trim.x ) + '" y="' + num( geo.trim.y ) +
				'" width="' + num( geo.trim.width ) + '" height="' + num( geo.trim.height ) +
				'" stroke="' + Infographic.COLORS.trim + '" stroke-width="' + num( stroke ) + '"/>'
			);

			if ( geo.margin ) {
				parts.push(
					'<rect x="' + num( geo.margin.x ) + '" y="' + num( geo.margin.y ) +
					'" width="' + num( geo.margin.width ) + '" height="' + num( geo.margin.height ) +
					'" stroke="' + Infographic.COLORS.margin + '" stroke-width="' + num( stroke ) +
					'" stroke-dasharray="' + num( stroke * 4 ) + '"/>'
				);
			}

			if ( geo.safe ) {
				parts.push(
					'<rect x="' + num( geo.safe.x ) + '" y="' + num( geo.safe.y ) +
					'" width="' + num( geo.safe.width ) + '" height="' + num( geo.safe.height ) +
					'" stroke="' + Infographic.COLORS.safe + '" stroke-width="' + num( stroke ) +
					'" stroke-dasharray="' + num( stroke * 3 ) + '"/>'
				);
			}

			parts.push(
				'<path d="M ' + num( geo.docWidth / 2 ) + ' 0 V ' + num( geo.docHeight ) +
				' M 0 ' + num( geo.docHeight / 2 ) + ' H ' + num( geo.docWidth ) +
				'" stroke="' + Infographic.COLORS.grid + '" stroke-width="' + num( stroke * 0.75 ) +
				'" stroke-dasharray="' + num( stroke * 3 ) + '"/>'
			);

			parts.push( '</g>' );

			parts.push(
				'<text x="' + num( geo.trim.x + ( font * 0.5 ) ) + '" y="' + num( geo.trim.y + ( font * 1.4 ) ) +
				'" font-family="Helvetica, Arial, sans-serif" font-size="' + num( font ) + '" fill="#6b7280">' +
				escapeXml(
					format.name + '  ' +
					Convert.dimensions( format.width, format.height, format.unit ) + '  ·  ' +
					format.aspect_ratio
				) +
				'</text>'
			);

			parts.push( '</svg>' );

			return parts.join( '\n' );
		},

		/**
		 * Trigger a browser download for a Blob.
		 *
		 * @param {Blob}   blob     Data.
		 * @param {string} filename Suggested file name.
		 */
		download: function ( blob, filename ) {
			var url = window.URL.createObjectURL( blob );
			var link = document.createElement( 'a' );

			link.href = url;
			link.download = filename;
			link.rel = 'noopener';
			link.style.position = 'absolute';
			link.style.left = '-9999px';

			document.body.appendChild( link );
			link.click();

			window.setTimeout( function () {
				document.body.removeChild( link );
				window.URL.revokeObjectURL( url );
			}, 1000 );
		},

		/**
		 * A safe file name for a format.
		 *
		 * @param {Object} format    Format record.
		 * @param {string} type      Template type.
		 * @param {string} extension File extension without the dot.
		 * @return {string} File name.
		 */
		filename: function ( format, type, extension ) {
			return ( format.id || 'size-guide' ) + '-' + type + '.' + extension;
		},

		/**
		 * Download the SVG template.
		 *
		 * @param {Object} format  Format record.
		 * @param {string} type    "clean" or "guide".
		 * @param {Object} strings Translated labels.
		 */
		downloadSvg: function ( format, type, strings ) {
			var svg = Templates.buildSvg( format, type, strings );
			var blob = new window.Blob( [ svg ], { type: 'image/svg+xml;charset=utf-8' } );

			Templates.download( blob, Templates.filename( format, type, 'svg' ) );
		},

		/**
		 * Rasterise the template and download it as a PNG.
		 *
		 * Falls back to the SVG download when the browser cannot rasterise.
		 *
		 * @param {Object}   format   Format record.
		 * @param {string}   type     "clean" or "guide".
		 * @param {Object}   strings  Translated labels.
		 * @param {Function} onError  Optional failure callback.
		 */
		downloadPng: function ( format, type, strings, onError ) {
			var svg = Templates.buildSvg( format, type, strings );
			var geo = Infographic.geometry( format, {} );
			var dpi = format.dpi || 72;

			var pixelWidth = 'px' === format.unit
				? Math.round( geo.docWidth )
				: Convert.toPixels( geo.docWidth, format.unit, dpi );
			var pixelHeight = 'px' === format.unit
				? Math.round( geo.docHeight )
				: Convert.toPixels( geo.docHeight, format.unit, dpi );

			// Keep very large print sizes inside what a canvas can hold.
			var maxSide = 8000;
			var limit = Math.max( pixelWidth, pixelHeight );
			if ( limit > maxSide ) {
				var factor = maxSide / limit;
				pixelWidth = Math.round( pixelWidth * factor );
				pixelHeight = Math.round( pixelHeight * factor );
			}

			var canvas = document.createElement( 'canvas' );
			canvas.width = pixelWidth;
			canvas.height = pixelHeight;

			var context = canvas.getContext( '2d' );
			if ( ! context ) {
				Templates.downloadSvg( format, type, strings );
				return;
			}

			var image = new window.Image();
			var source = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent( svg );

			image.onload = function () {
				context.fillStyle = '#ffffff';
				context.fillRect( 0, 0, pixelWidth, pixelHeight );
				context.drawImage( image, 0, 0, pixelWidth, pixelHeight );

				if ( canvas.toBlob ) {
					canvas.toBlob( function ( blob ) {
						if ( blob ) {
							Templates.download( blob, Templates.filename( format, type, 'png' ) );
						} else if ( onError ) {
							onError();
						}
					}, 'image/png' );
				} else if ( onError ) {
					onError();
				}
			};

			image.onerror = function () {
				// Some browsers refuse to rasterise inline SVG; the vector file still works.
				Templates.downloadSvg( format, type, strings );
			};

			image.src = source;
		},

		/**
		 * Open a print window for the template, which also covers "save as PDF".
		 *
		 * @param {Object} format  Format record.
		 * @param {string} type    "clean" or "guide".
		 * @param {Object} strings Translated labels.
		 */
		print: function ( format, type, strings ) {
			var svg = Templates.buildSvg( format, type, strings );
			var win = window.open( '', '_blank' );

			if ( ! win ) {
				Templates.downloadSvg( format, type, strings );
				return;
			}

			var unitSuffix = 'px' === format.unit ? 'px' : format.unit;
			var geo = Infographic.geometry( format, {} );

			win.document.write(
				'<!doctype html><html><head><meta charset="utf-8">' +
				'<title>' + escapeXml( format.platform_name + ' — ' + format.name ) + '</title>' +
				'<style>@page{size:' + num( geo.docWidth ) + unitSuffix + ' ' + num( geo.docHeight ) + unitSuffix +
				';margin:0}html,body{margin:0;padding:0}svg{display:block;width:100%;height:auto}</style>' +
				'</head><body>' + svg.replace( /^<\?xml[^>]*\?>\s*/, '' ) + '</body></html>'
			);
			win.document.close();
			win.focus();

			window.setTimeout( function () {
				win.print();
			}, 250 );
		}
	};

	SizeGuide.Templates = Templates;
}( window, document ) );
